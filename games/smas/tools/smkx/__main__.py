"""Translate the pinned SMAS disassembly and the user's ROM to 68030 source.

    python3 -m tools.smkx "assets/Super Mario All-Stars (USA).sfc" build/smasx

The translator comes from the F030SMK port (hence the package name) by way
of F030SMW (LoROM, Asar walker); see analysis/translator.md. Writes, all
derived from the ROM and therefore untracked:
    smas.sfc     the ROM image (copier header removed) the runtime links in
    smk_code_NNN.s  the translated program
    report.txt   placement, analysis and emission findings
"""

from __future__ import annotations

import argparse
import collections
import hashlib
import os
import sys
import time
import zipfile
from pathlib import Path

from . import analyze, emit, listing, liveness

ROOT = Path(__file__).resolve().parents[2]
DISASM = ROOT / "third_party/SMW-SMAS-SMASW-Disassembly"
# Yoshifanatic1's framework (Asar): the ROM map places the routine macros of
# SMAS/, SMB1/, SMBLL/, SMB2U/ and SMB3/ at fixed addresses, bank by bank.
LISTING = DISASM / "SMAS/RomMap/ROM_Map_SMAS_U.asm"
EXTRA = ROOT / "tools/smkx/dispatch_targets.txt"
PROBES = ROOT / "tools/smkx/probes.txt"
TRACES = ROOT / "tools/smkx/traces.txt"   # every execution, from SMKX_TRACE_FROM on
# The U.S. release as ROM_Map_SMAS_U.asm describes it: LoROM, 2 MiB, ROM +
# RAM + SRAM, !Define_Global_BaseROMMD5Hash of the headerless image.
ROM_SIZE = 0x200000
US_MD5 = "53c038150ba00d5f8d8574b4d36283f2"


def load_rom(path: Path) -> bytes:
    """The U.S. ROM from a .sfc/.smc file or a ZIP holding one; a 512-byte
    copier header is dropped. Checked by the MD5 the disassembly's ROM map
    gives for the U.S. release."""
    if path.suffix.lower() == ".zip":
        with zipfile.ZipFile(path) as z:
            names = [n for n in z.namelist() if n.lower().endswith((".sfc", ".smc"))]
            if len(names) != 1:
                raise SystemExit(f"{path}: expected one .sfc/.smc, found {names}")
            rom = z.read(names[0])
    else:
        rom = path.read_bytes()
    if len(rom) == ROM_SIZE + 512:
        rom = rom[512:]
    if len(rom) != ROM_SIZE:
        raise SystemExit(f"{path}: {len(rom)} bytes, expected {ROM_SIZE} (plus an optional 512-byte header)")
    digest = hashlib.md5(rom).hexdigest()
    if digest != US_MD5:
        raise SystemExit(f"{path}: MD5 {digest} is not the U.S. release ({US_MD5}, from ROM_Map_SMAS_U.asm)")
    print(f"ROM: U.S. release, MD5 {digest}")
    return rom


def flag_tables() -> str:
    """CCR/P conversion tables for the runtime (68k CCR: X N Z V C = 16 8 4 2 1)."""
    def rows(name, values):
        out = [f"{name}:"]
        for i in range(0, len(values), 16):
            out.append("\tdc.b\t" + ",".join(f"${v:02X}" for v in values[i:i + 16]))
        return out
    cmpfix = [(c & 0x0F) | (0 if c & 1 else 0x10) for c in range(32)]
    x2c = [(c & 0x1E) | ((c >> 4) & 1) for c in range(32)]
    ccr2p = [((c & 8) << 4) | ((c & 2) << 5) | ((c & 4) >> 1) | ((c >> 4) & 1) for c in range(32)]
    p2ccr = [(0x11 if p & 1 else 0) | (4 if p & 2 else 0) | (2 if p & 0x40 else 0) | (8 if p & 0x80 else 0)
             for p in range(256)]
    lines = ["; Generated by tools/smkx: CCR and P conversion tables.", "\tsection\tdata,data",
             "\txdef\trt_inc8,rt_dec8,rt_cmpfix,rt_x2c,rt_ccr2p,rt_p2ccr"]
    lines += rows("rt_inc8", [(i + 1) & 0xFF for i in range(256)])
    lines += rows("rt_dec8", [(i - 1) & 0xFF for i in range(256)])
    lines += rows("rt_cmpfix", cmpfix) + rows("rt_x2c", x2c) + rows("rt_ccr2p", ccr2p)
    lines += rows("rt_p2ccr", p2ccr)
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("rom", type=Path)
    ap.add_argument("out", type=Path)
    args = ap.parse_args()
    out: Path = args.out
    out.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    rom = load_rom(args.rom)
    (out / "smas.sfc").write_bytes(rom)
    if not hasattr(listing, "parse_smas"):
        raise SystemExit("SMAS placement is not written yet: see ROADMAP.md, step 1")
    lst = listing.parse_smas(LISTING, rom)
    prog = analyze.analyse(lst, EXTRA)
    t1 = time.time()
    live = liveness.compute(prog)
    files, em = emit.emit(prog, live, analyze.extra_targets(PROBES), analyze.extra_targets(TRACES))
    for old in out.glob("smk_code_*.s"):
        old.unlink()
    for name, text in files.items():
        (out / name).write_text(text)
    (out / "sources.txt").write_text("\n".join(sorted(files)) + "\n")
    (out / "smkx_tables.s").write_text(flag_tables())
    t2 = time.time()

    report = []
    procs = prog.procs.values()
    addrs = {a for p in procs for a in p.insns}
    covered = {analyze.rom_index(a) for a in addrs} & set(lst.insn_at)
    report.append(f"listing instructions placed and ROM-checked: {len(lst.insn_at)}")
    report.append(f"procedures: {len(prog.procs)} over {len({k[0] for k in prog.procs})} entries")
    report.append(f"instruction addresses reached: {len(addrs)}; listing instructions reached: {len(covered)}")
    report.append(f"nodes: {sum(len(v) for p in procs for v in p.states.values())}")
    report.append(f"exit contexts: {len(em.exit_ids)}")
    report.append(f"analysis {t1 - t0:.1f}s, liveness+emit {t2 - t1:.1f}s")
    names = {1: "C", 2: "Z", 4: "N", 8: "V"}
    saves = sorted(em.ccr_saves.items(), key=lambda kv: -kv[1])
    report.append(f"flag saves around nodes: {sum(em.ccr_saves.values())} ("
                  + ", ".join("".join(n for b, n in names.items() if m & b) + f" {c}" for m, c in saves) + ")")
    report.append("")
    report.append(f"## unsupported nodes ({len(em.unsupported)})")
    kinds = collections.Counter(u.split(": ", 1)[1] for u in em.unsupported)
    report.extend(f"  {n:5} {k}" for k, n in kinds.most_common())
    report.append("")
    traps = collections.Counter(r for p in procs for r in p.traps.values())
    report.append(f"## trap nodes ({sum(traps.values())})")
    report.extend(f"  {n:5} {k}" for k, n in traps.most_common(40))
    report.append("")
    probs = [f"{p.name}: {x}" for p in procs for x in p.problems]
    report.append(f"## analysis findings ({len(probs)})")
    report.extend("  " + x for x in probs[:400])
    report.append("")
    report.append("## exit contexts (rt_badexit reports the id)")
    for ctx, i in sorted(em.exit_ids.items(), key=lambda kv: kv[1]):
        report.append(f"  {i:3}  {ctx.short()}")
    report.append("")
    report.append("## label names that disagree with their placement")
    report.extend("  " + w for w in lst.warnings)
    (out / "report.txt").write_text("\n".join(report) + "\n")
    print("\n".join(report[:9]))
    print(f"unsupported: {len(em.unsupported)}  traps: {sum(traps.values())}  findings: {len(probs)}")


if __name__ == "__main__":
    # The analysis iterates sets of tuples that contain strings, and Python
    # randomises string hashes per process. A fixed seed makes the same ROM
    # and listing always produce byte-identical sources.
    if os.environ.get("PYTHONHASHSEED") != "0":
        os.environ["PYTHONHASHSEED"] = "0"
        os.execv(sys.executable, [sys.executable, "-m", "tools.smkx", *sys.argv[1:]])
    sys.exit(main())
