"""Vectors for UPDTEST.TOS: the translated DSP-1 against upd7725.UPD.

    python3 -m tools.smkx.updtest gen  assets/dsp1.bin build/smkx
    python3 -m tools.smkx.updtest check build/smkx build/smkx/hatari-stderr.log

gen writes updtest_ops.i (host operations: write a DR byte, read a DR byte,
read SR) and updtest_expect.txt (the bytes the interpreter reads). check
compares the harness's printed bytes with the expected ones.
"""

from __future__ import annotations

import random
import re
import sys
from pathlib import Path

from .upd7725 import UPD, load_firmware

W, R, S = 1, 2, 3


def script(seed: int = 1) -> list[tuple[int, int]]:
    rnd = random.Random(seed)
    ops: list[tuple[int, int]] = []

    def cmd(c, params, results):
        ops.append((W, c))
        for p in params:
            ops.append((W, p & 0xFF))
            ops.append((W, (p >> 8) & 0xFF))
        for _ in range(results):
            ops.append((S, 0))
            ops.append((R, 0))
            ops.append((R, 0))

    r16 = lambda lo=-0x8000, hi=0x7FFF: rnd.randint(lo, hi) & 0xFFFF
    for _ in range(128):                       # SMK's reset: 128 null bytes
        ops.append((W, 0x80))
    for _ in range(12):
        cmd(0x00, [r16(), r16()], 1)
        cmd(0x04, [r16(), r16(0, 0x7FFF)], 2)
        cmd(0x28, [r16(-4000, 4000), r16(-4000, 4000), 0], 1)
        cmd(0x10, [r16(1, 0x7FFF), r16(-8, 8)], 2)
        cmd(0x0C, [r16(), r16(), r16()], 2)
        cmd(0x08, [r16(), r16(), r16()], 2)
    for _ in range(8):
        # projection, as SMK sets it up, then 24 raster lines and 6 objects
        params = [r16(0, 0x3FFF), r16(0, 0x3FFF), 0, r16(0x40, 0x400), r16(0x20, 0x100),
                  r16(), r16(0x1000, 0x3800)]
        cmd(0x02, params, 4)
        cmd(0x0A, [r16(-0x40, 0x40)], 0)
        for _ in range(24 * 4):
            ops.append((S, 0))
            ops.append((R, 0))
            ops.append((R, 0))
        for _ in range(4):                     # SMK ends the stream with $8000 x 4
            ops.append((W, 0x00))
            ops.append((W, 0x80))
        for _ in range(6):
            cmd(0x06, [r16(0, 0xFFFF), r16(0, 0xFFFF), 0], 3)
    return ops


def expected(upd: UPD, ops) -> list[int]:
    out = []
    for kind, v in ops:
        if kind == W:
            upd.host_write_dr(v)
        elif kind == R:
            out.append(upd.host_read_dr())
        else:
            out.append(upd.host_read_sr())
    return out


def gen(firmware: Path, outdir: Path) -> None:
    prog, rom = load_firmware(firmware)
    ops = script()
    exp = expected(UPD(prog, rom), ops)
    lines = ["; Generated by tools/smkx/updtest.py: host operations for UPDTEST.TOS",
             f"UPDTEST_OPS\tequ\t{len(ops)}", "updtest_ops:"]
    for i in range(0, len(ops), 16):
        lines.append("\tdc.b\t" + ",".join(f"{k},${v:02X}" for k, v in ops[i:i + 16]))
    (outdir / "updtest_ops.i").write_text("\n".join(lines) + "\n")
    (outdir / "updtest_expect.txt").write_text(" ".join(f"{b:02X}" for b in exp) + "\n")
    print(f"{len(ops)} host operations, {len(exp)} bytes read")


def check(outdir: Path, log: Path) -> int:
    exp = (outdir / "updtest_expect.txt").read_text().split()
    got = []
    for line in log.read_text(errors="replace").splitlines():
        m = re.fullmatch(r"UPD ((?:[0-9A-F]{2} ?)+)", line.strip())
        if m:
            got += m.group(1).split()
    bad = [i for i, (a, b) in enumerate(zip(exp, got)) if a != b]
    print(f"expected {len(exp)} bytes, harness printed {len(got)}, mismatches {len(bad)}")
    for i in bad[:10]:
        print(f"  byte {i}: expected {exp[i]}, got {got[i]}")
    return 0 if not bad and len(got) == len(exp) else 1


if __name__ == "__main__":
    if sys.argv[1] == "gen":
        gen(Path(sys.argv[2]), Path(sys.argv[3]))
    else:
        sys.exit(check(Path(sys.argv[2]), Path(sys.argv[3])))
