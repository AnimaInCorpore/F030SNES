"""Compile regions of the DSP-1 program to value-level C (exact).

    python3 -m tools.smkx.upd2c assets/dsp1.bin build/smkx/dsp1_regions.c

Each region starts at a loop or command head and runs until one of its exit
program counters, a host poll (JRQM/JNRQM) or a return out of the region.
The generated function mirrors upd7725.UPD instruction by instruction:
registers and the twelve flags are locals (gcc drops what nothing reads), M
and N are formed from K and L where an instruction selects them (the chip
forms them at the end of every instruction from the same K and L), the
four-level return stack is kept, and everything is written back to the
state block on exit. It returns the program counter the translated firmware
continues at. tools/dsp1_hle_test.c checks each region against vectors from
the interpreter (tools/smkx/dsp1_hle.py --vectors).
"""

from __future__ import annotations

import argparse
from pathlib import Path

from .upd7725 import load_firmware

# name -> (entry, exits)
REGIONS = {
    "raster": (0x364, (0x384, 0x392)),
    "project": (0x3AE, (0x412,)),
}

COND = {
    0x080: "!fa_c", 0x082: "fa_c", 0x084: "!fb_c", 0x086: "fb_c",
    0x088: "!fa_z", 0x08A: "fa_z", 0x08C: "!fb_z", 0x08E: "fb_z",
    0x090: "!fa_ov0", 0x092: "fa_ov0", 0x094: "!fb_ov0", 0x096: "fb_ov0",
    0x098: "!fa_ov1", 0x09A: "fa_ov1", 0x09C: "!fb_ov1", 0x09E: "fb_ov1",
    0x0A0: "!fa_s0", 0x0A2: "fa_s0", 0x0A4: "!fb_s0", 0x0A6: "fb_s0",
    0x0A8: "!fa_s1", 0x0AA: "fa_s1", 0x0AC: "!fb_s1", 0x0AE: "fb_s1",
    0x0B0: "(dp & 15) == 0", 0x0B1: "(dp & 15) != 0",
    0x0B2: "(dp & 15) == 15", 0x0B3: "(dp & 15) != 15",
}
POLLS = (0x0BC, 0x0BE)

HEADER = r"""/* Generated by tools/smkx/upd2c.py from assets/dsp1.bin. Do not commit.
 * Value-level DSP-1 regions (see the generator); exact against the
 * interpreter. Freestanding. */
#include "dsp1_hle.h"

#define M(k, l) ((uint16_t)(((int32_t)(int16_t)(k) * (int16_t)(l)) >> 15))
#define N(k, l) ((uint16_t)(((int32_t)(int16_t)(k) * (int16_t)(l)) << 1))

/* The ALU (upd7725.UPD.alu): op, p (operand), q (accumulator), c (the
 * other accumulator's carry); flags as 0/1 locals. */
static inline __attribute__((unused)) uint16_t alu(int op, uint16_t p, uint16_t q, int c,
                           int *ov0, int *ov1, int *z, int *cy, int *s0, int *s1)
{
    uint32_t r;
    switch (op) {
    case 1: r = q | p; break;
    case 2: r = q & p; break;
    case 3: r = q ^ p; break;
    case 4: r = (uint32_t)q - p; break;
    case 5: r = (uint32_t)q + p; break;
    case 6: r = (uint32_t)q - p - c; break;
    case 7: r = (uint32_t)q + p + c; break;
    case 8: r = (uint32_t)q - 1; p = 1; break;
    case 9: r = (uint32_t)q + 1; p = 1; break;
    case 10: r = (uint16_t)~q; break;
    case 11: r = (q >> 1) | (q & 0x8000); break;
    case 12: r = ((uint32_t)q << 1) | (c ? 1 : 0); break;
    case 13: r = ((uint32_t)q << 2) | 3; break;
    case 14: r = ((uint32_t)q << 4) | 15; break;
    default: r = (uint16_t)((q << 8) | (q >> 8)); break;
    }
    uint16_t v = (uint16_t)r;
    *s0 = v >> 15;
    *z = v == 0;
    if (op == 1 || op == 2 || op == 3 || op == 10 || op == 13 || op == 14 || op == 15) {
        *cy = *ov0 = *ov1 = 0;
    } else if (op >= 4 && op <= 9) {
        if (op & 1) {
            *ov0 = ((q ^ v) & (p ^ v) & 0x8000) != 0;
            *cy = v < q;
        } else {
            *ov0 = ((q ^ v) & (q ^ p) & 0x8000) != 0;
            *cy = v > q;
        }
        if (*ov0) {
            *s1 = *ov1 ^ ((v & 0x8000) ? 0 : 1);
            *ov1 ^= 1;
        }
    } else if (op == 11) {
        *cy = q & 1;
        *ov0 = *ov1 = 0;
    } else if (op == 12) {
        *cy = q >> 15;
        *ov0 = *ov1 = 0;
    }
    return v;
}
"""


def fields(op: int) -> dict:
    return dict(kind=op >> 22, psel=(op >> 20) & 3, alu=(op >> 16) & 15, asl=(op >> 15) & 1,
                dpl=(op >> 13) & 3, dphm=(op >> 9) & 15, rpdcr=(op >> 8) & 1,
                src=(op >> 4) & 15, dst=op & 15, brch=(op >> 13) & 0x1FF, na=(op >> 2) & 0x7FF,
                imm=(op >> 6) & 0xFFFF)


# Firmware subroutines replaced by closed-form C (entered by CALL/JMP at the
# key only: nothing else in the program jumps into their middle).
NATIVE = {
    # NORM, $03A-$041: DP = 0; A = 0 -> L = B = 0 with the flags of AND A,A
    # and XOR B,B. Otherwise A doubles while ADD A,A does not overflow (s
    # times, s <= 15; DP counts them in its low nibble); A = L = A << s,
    # B -= s. A's flags are those of the final, overflowing ADD (AND A,A
    # cleared OV1 first, so OV1 ends 1 and S1 is the sum's sign inverted);
    # B's those of SUB B,s.
    0x03A: """
{
dp = 0;
if (a == 0) {
l = 0;
fa_z = 1; fa_s0 = 0; fa_c = 0; fa_ov0 = 0; fa_ov1 = 0;
b = 0;
fb_z = 1; fb_s0 = 0; fb_c = 0; fb_ov0 = 0; fb_ov1 = 0;
} else {
uint16_t x = a, v, q, w;
/* redundant sign bits: leading zeros of x (or ~x) in 16 bits, minus one;
 * the | $8000 keeps clz defined for x = $FFFF (sh = 15) */
uint16_t y = (x & 0x8000) ? (uint16_t)~x : x;
unsigned sh = (unsigned)__builtin_clz(((uint32_t)y << 16) | 0x8000) - 1;
int o;
x = (uint16_t)(x << sh);
v = (uint16_t)(x << 1);
a = x; l = x;
fa_s0 = v >> 15; fa_z = v == 0; fa_c = v < x; fa_ov0 = 1;
fa_s1 = (v & 0x8000) ? 0 : 1; fa_ov1 = 1;
q = b; w = (uint16_t)(q - sh);
o = ((q ^ w) & (q ^ (uint16_t)sh) & 0x8000) != 0;
fb_s0 = w >> 15; fb_z = w == 0; fb_c = w > q; fb_ov0 = o;
if (o) { fb_s1 = fb_ov1 ^ ((w & 0x8000) ? 0 : 1); fb_ov1 ^= 1; }
b = w;
}
}
""",
}


class Region:
    def __init__(self, program: list[int], name: str, entry: int, exits: tuple[int, ...]):
        from .upd2m68k import liveness      # upd2m68k imports REGIONS from here
        self.program, self.name, self.entry, self.exits = program, name, entry, set(exits)
        self.live = liveness(program)       # flags live after each instruction
        self.nodes: set[int] = set()
        self.returns: set[int] = set()
        self.discover()

    def successors(self, pc: int) -> list[int]:
        if pc in NATIVE:
            return []                                   # returns like RT
        f = fields(self.program[pc])
        nxt = (pc + 1) & 0x7FF
        if f["kind"] == 1:
            return []                                   # RT: the return sites
        if f["kind"] == 2:
            if f["brch"] in POLLS:
                return []
            if f["brch"] == 0x140:
                self.returns.add(nxt)
                return [f["na"], nxt]
            if f["brch"] == 0x100:
                return [f["na"]]
            return [f["na"], nxt]
        return [nxt]

    def discover(self) -> None:
        todo = [self.entry]
        while todo:
            pc = todo.pop()
            if pc in self.nodes or (pc in self.exits and pc != self.entry):
                continue
            self.nodes.add(pc)
            todo.extend(self.successors(pc))
        # return sites are only reached through RT
        todo = list(self.returns)
        while todo:
            pc = todo.pop()
            if pc in self.nodes or pc in self.exits:
                continue
            self.nodes.add(pc)
            todo.extend(self.successors(pc))
            todo.extend(r for r in self.returns if r not in self.nodes)

    # -- code ---------------------------------------------------------------
    def goto(self, pc: int) -> str:
        if pc in self.nodes and not (pc in self.exits and pc != self.entry):
            return f"goto L{pc:03X};"
        return f"{{ pc = 0x{pc:03X}; goto out; }}"

    def src(self, src: int) -> str:
        return {0: "trb", 1: "a", 2: "b", 3: "tr", 4: "dp", 5: "rp", 6: "rom[rp & 0x3FF]",
                7: "(uint16_t)(0x8000 - fa_s1)", 8: "(sr |= 0x8000, dr)", 9: "dr", 10: "sr",
                11: "0", 12: "0", 13: "k", 14: "l", 15: "ram[dp & 0xFF]"}[src]

    def dst(self, dst: int, v: str) -> list[str]:
        return {
            0: [], 1: [f"a = {v};"], 2: [f"b = {v};"], 3: [f"tr = {v};"],
            4: [f"dp = {v} & 0xFF;"], 5: [f"rp = {v} & 0x3FF;"],
            6: [f"dr = {v};", "sr |= 0x8000;"], 7: [f"sr = (sr & 0x907C) | ({v} & 0x6F83);"],
            8: [], 9: [], 10: [f"k = {v};"], 11: [f"k = {v};", "l = rom[rp & 0x3FF];"],
            12: [f"l = {v};", "k = ram[(dp | 0x40) & 0xFF];"], 13: [f"l = {v};"],
            14: [f"trb = {v};"], 15: [f"ram[dp & 0xFF] = {v};"],
        }[dst]

    def ret(self) -> list[str]:
        """RT: pop the return address and continue there."""
        out = ["{ uint16_t r = st0; st0 = st1; st1 = st2; st2 = st3;", "switch (r) {"]
        out += [f"case 0x{r:03X}: goto L{r:03X};" for r in sorted(self.returns) if r in self.nodes]
        out += ["default: pc = r; goto out; } }"]
        return out

    def instruction(self, pc: int) -> list[str]:
        if pc in NATIVE:
            return [f"L{pc:03X}:"] + NATIVE[pc].strip("\n").split("\n") + self.ret()
        op = self.program[pc]
        f = fields(op)
        out = [f"L{pc:03X}:"]
        nxt = (pc + 1) & 0x7FF
        if f["kind"] == 3:
            out += ["{", f"uint16_t idb = 0x{f['imm']:04X};"] + self.dst(f["dst"], "idb") + ["}"]
            out.append(self.goto(nxt))
            return out
        if f["kind"] == 2:
            b = f["brch"]
            if b in POLLS:
                return out + [f"{{ pc = 0x{pc:03X}; goto out; }}"]
            if b == 0x100:
                return out + [self.goto(f["na"])]
            if b == 0x140:
                return out + ["st3 = st2; st2 = st1; st1 = st0;", f"st0 = 0x{nxt:03X};", self.goto(f["na"])]
            return out + [f"if ({COND[b]}) {self.goto(f['na'])}", self.goto(nxt)]
        out += ["{", f"uint16_t idb = {self.src(f['src'])};"]
        if f["alu"]:
            p = ["ram[dp & 0xFF]", "idb", "M(k, l)", "N(k, l)"][f["psel"]]
            out += self.alu(pc, f["alu"], "ab"[f["asl"]], p)
        out += self.dst(f["dst"], "idb")
        if f["dpl"] == 1:
            out.append("dp = (dp & 0xF0) | ((dp + 1) & 0x0F);")
        elif f["dpl"] == 2:
            out.append("dp = (dp & 0xF0) | ((dp - 1) & 0x0F);")
        elif f["dpl"] == 3:
            out.append("dp &= 0xF0;")
        if f["dphm"]:
            out.append(f"dp ^= 0x{f['dphm'] << 4:02X};")
        if f["rpdcr"]:
            out.append("rp = (rp - 1) & 0x3FF;")
        out.append("}")
        if f["kind"] == 1:
            return out + self.ret()
        out.append(self.goto(nxt))
        return out

    def alu(self, pc: int, op: int, x: str, p: str) -> list[str]:
        """The ALU step of alu() in the header, computing only the flags
        live after it (upd2m68k.liveness: add/subtract read OV1 and S1,
        so an S1 computed later always sees a correct OV1)."""
        from .upd2m68k import BIT
        live = self.live[pc]
        def lv(n):
            return bool(live & BIT[f"{x}_{n}"])
        q, c = x, ("fb_c" if x == "a" else "fa_c")
        fl = lambda n: f"f{x}_{n}"          # noqa: E731
        expr = {1: f"(uint32_t)({q} | pv)", 2: f"(uint32_t)({q} & pv)", 3: f"(uint32_t)({q} ^ pv)",
                4: f"(uint32_t){q} - pv", 5: f"(uint32_t){q} + pv", 6: f"(uint32_t){q} - pv - {c}",
                7: f"(uint32_t){q} + pv + {c}", 8: f"(uint32_t){q} - 1", 9: f"(uint32_t){q} + 1",
                10: f"(uint32_t)(uint16_t)~{q}", 11: f"(uint32_t)(({q} >> 1) | ({q} & 0x8000))",
                12: f"(((uint32_t){q} << 1) | ({c} ? 1 : 0))", 13: f"(((uint32_t){q} << 2) | 3)",
                14: f"(((uint32_t){q} << 4) | 15)"}.get(op, f"(uint32_t)(uint16_t)(({q} << 8) | ({q} >> 8))")
        pv = "1" if op in (8, 9) else p
        out = ["{", f"uint16_t pv = {pv};" if op in range(1, 10) else "", f"uint16_t v = (uint16_t)({expr});"]
        if op not in range(1, 10):
            out[1] = ""
        if lv("s0"):
            out.append(f"{fl('s0')} = v >> 15;")
        if lv("z"):
            out.append(f"{fl('z')} = v == 0;")
        if op in (1, 2, 3, 10, 13, 14, 15):
            out += [f"{fl(n)} = 0;" for n in ("c", "ov0", "ov1") if lv(n)]
        elif 4 <= op <= 9:
            if op & 1:
                ov, cy = f"((({q} ^ v) & (pv ^ v) & 0x8000) != 0)", f"(v < {q})"
            else:
                ov, cy = f"((({q} ^ v) & ({q} ^ pv) & 0x8000) != 0)", f"(v > {q})"
            if lv("ov0") or lv("ov1") or lv("s1"):
                out.append(f"int o = {ov};")
                if lv("ov0"):
                    out.append(f"{fl('ov0')} = o;")
                if lv("ov1") or lv("s1"):
                    body = []
                    if lv("s1"):
                        body.append(f"{fl('s1')} = {fl('ov1')} ^ ((v & 0x8000) ? 0 : 1);")
                    if lv("ov1"):
                        body.append(f"{fl('ov1')} ^= 1;")
                    out.append("if (o) { " + " ".join(body) + " }")
            if lv("c"):
                out.append(f"{fl('c')} = {cy};")
        elif op == 11:
            if lv("c"):
                out.append(f"{fl('c')} = {q} & 1;")
            out += [f"{fl(n)} = 0;" for n in ("ov0", "ov1") if lv(n)]
        elif op == 12:
            if lv("c"):
                out.append(f"{fl('c')} = {q} >> 15;")
            out += [f"{fl(n)} = 0;" for n in ("ov0", "ov1") if lv(n)]
        out += [f"{q} = v;", "}"]
        return [l for l in out if l]

    def c(self) -> str:
        body = []
        for pc in sorted(self.nodes):
            body += self.instruction(pc)
        flags = [f"f{x}_{n}" for x in "ab" for n in ("ov0", "ov1", "z", "c", "s0", "s1")]
        lines = [f"unsigned dsp1_region_{self.name}(UpdState *s, uint16_t *ram, const uint16_t *rom)", "{",
                 "uint16_t a = s->a, b = s->b, k = s->k, l = s->l, dp = s->dp, rp = s->rp;",
                 "uint16_t tr = s->tr, trb = s->trb, dr = s->dr, sr = s->sr;",
                 "uint16_t st0 = s->stack[0], st1 = s->stack[1], st2 = s->stack[2], st3 = s->stack[3];",
                 "unsigned pc;"]
        for i, fl in enumerate(flags):
            src = "fa" if fl.startswith("fa") else "fb"
            lines.append(f"int {fl} = s->{src}[{i % 6}] != 0;")
        lines.append(f"goto L{self.entry:03X};")
        lines += body
        lines += ["out:",
                  "s->a = a; s->b = b; s->k = k; s->l = l; s->dp = dp; s->rp = rp;",
                  "s->tr = tr; s->trb = trb; s->dr = dr; s->sr = sr;",
                  "s->stack[0] = st0; s->stack[1] = st1; s->stack[2] = st2; s->stack[3] = st3;"]
        for i, fl in enumerate(flags):
            dst = "fa" if fl.startswith("fa") else "fb"
            lines.append(f"s->{dst}[{i % 6}] = {fl} ? 0xFF : 0;")
        lines += ["return pc;", "}"]
        return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("firmware", type=Path)
    ap.add_argument("out", type=Path)
    args = ap.parse_args()
    program, _ = load_firmware(args.firmware)
    parts = [HEADER]
    for name, (entry, exits) in REGIONS.items():
        r = Region(program, name, entry, exits)
        parts.append(f"\n/* {name}: ${entry:03X} to {', '.join(f'${x:03X}' for x in exits)}; "
                     f"{len(r.nodes)} instructions */\n")
        parts.append(r.c())
    # Flags live on entry to each instruction, for the vector test: flags
    # dead there may hold anything once regions skip dead flag updates.
    from .upd2m68k import liveness, flag_use_def
    live_out = liveness(program)
    live_in = []
    for pc, op in enumerate(program):
        use, dfn = flag_use_def(op)
        live_in.append(use | (live_out[pc] & ~dfn))
    parts.append("\n/* Flags live at each program counter: bits 0-5 = A's OV0 OV1 Z C S0 S1,\n"
                 " * bits 6-11 = B's (tools/smkx/upd2m68k.py BIT). */\n"
                 "const uint16_t dsp1_flags_live[2048] = {\n")
    for i in range(0, len(live_in), 16):
        parts.append("    " + ", ".join(f"0x{v:03X}" for v in live_in[i:i + 16]) + ",\n")
    parts.append("};\n")
    args.out.write_text("".join(parts))
    print(f"wrote {args.out}: " + ", ".join(f"{n} {len(Region(program, n, *REGIONS[n]).nodes)}" for n in REGIONS))


if __name__ == "__main__":
    main()
