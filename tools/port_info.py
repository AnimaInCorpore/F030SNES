#!/usr/bin/env python3
"""Write a port's info.i: the info screen every program shows at start, the files the player supplies (the ROM, for
SMK also the DSP-1 dump) with their sizes and checksums, and the start line of the log.  falcon/smkx_info.s reads
the files and checks them; the programs carry no game content.

    python3 tools/port_info.py <game> <out.i> --rom <rom.sfc> [--dsp1 <dsp1.bin>] [--wait <seconds>]

The file is rewritten only when its text changes, so make rebuilds the program only then.  The version is
$F030SNES_VERSION (tools/release.py sets it), else "dev".
"""
import argparse
import os
import textwrap
from pathlib import Path

from games import CONTROLS, GAMES

WIDTH = 39          # a Falcon in ST low resolution shows 40 columns; the 40th would wrap
DSP1_OFFSET, DSP1_BYTES, DSP1_FILE = 6144, 2048, 8192      # the data ROM inside the uPD77C25 dump


def checksum(data):
    """falcon/smkx_info.s: per big-endian long, sum = rol(sum, 1) + long."""
    assert len(data) % 4 == 0, "a file's checked bytes must be a multiple of 4"
    s = 0
    for i in range(0, len(data), 4):
        s = ((s << 1) | (s >> 31)) & 0xFFFFFFFF
        s = (s + int.from_bytes(data[i:i + 4], "big")) & 0xFFFFFFFF
    return s


def version():
    return os.environ.get("F030SNES_VERSION") or "dev"


def dc(text):
    """A dc.b line for ASCII text; CR LF ends the console lines."""
    out, run = [], ""
    for ch in text:
        if ch in "\r\n\x1b" or ch == '"':
            if run:
                out.append('"%s"' % run)
                run = ""
            out.append(str(ord(ch)))
        else:
            assert 32 <= ord(ch) < 127, "info text must be ASCII: %r" % ch
            run += ch
    if run:
        out.append('"%s"' % run)
    return "\tdc.b\t" + ",".join(out) + ",0"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("game", choices=sorted(GAMES))
    ap.add_argument("out", type=Path)
    ap.add_argument("--rom", type=Path, required=True, help="the ROM as the translator wrote it (no copier header)")
    ap.add_argument("--dsp1", type=Path, help="SMK: the DSP-1 dump, when the program runs its firmware")
    ap.add_argument("--wait", type=int, default=0, help="seconds the info screen stays (a key skips; 0: no wait)")
    a = ap.parse_args()
    g = GAMES[a.game]
    v = version()

    rom = a.rom.read_bytes()
    files = [("ROM", "smkx_rom", len(rom), 0, len(rom), checksum(rom), g["files"][0][0])]
    if a.dsp1:
        d = a.dsp1.read_bytes()
        assert len(d) == DSP1_FILE, "%s: %d bytes, not %d" % (a.dsp1, len(d), DSP1_FILE)
        files.append(("DSP1", "upd_rom", DSP1_BYTES, DSP1_OFFSET, DSP1_FILE,
                      checksum(d[DSP1_OFFSET:DSP1_OFFSET + DSP1_BYTES]), g["files"][1][0]))

    lines = ["F030SNES " + v] + textwrap.wrap(g["title"], WIDTH) + ["-" * WIDTH]
    lines += textwrap.wrap("A SNES game: its 65816 code translated to 68030, the DSP56001 draws the picture.", WIDTH)
    lines += [""] + textwrap.wrap("Highly experimental: far too slow for play, the rendering above all.", WIDTH)
    lines += textwrap.wrap("Reaches: " + g["state"] + ".", WIDTH)
    lines += ["", "Keys (pad 1, by QWERTY position):"] + [" " + c for c in CONTROLS]
    lines += ["", "Files next to the program (.SMC too):"]
    for line in lines:
        assert len(line) <= WIDTH, "info line too long: %r" % line

    out = ["; Generated by tools/port_info.py from tools/games.py and the player's files.  Do not edit or commit:",
           "; the checksums are derived from the ROM.", "",
           "INFO_WAIT\tequ\t%d\t\t; seconds the info screen stays, a key skips (0: no wait)" % a.wait]
    for tag, _, nbytes, _, _, s, _ in files:
        out.append("%s_BYTES\tequ\t$%X" % (tag, nbytes))
        out.append("%s_SUM\tequ\t$%08X" % (tag, s))
    out += ["", "\tsection\tdata,data", "info_text:", dc("\x1bE\x1bf" + "\r\n".join(lines) + "\r\n")]
    out += ["info_wait:", dc("\r\nStarting in %d s, or press a key." % a.wait)]
    out += ["msg_start:", dc("F030SNES %s: %s starting\n" % (v, g["title"]))]
    for i, (tag, _, _, _, _, _, name) in enumerate(files):
        out += ["info_name%d:" % i, dc(name)]
        if name.endswith(".SFC"):
            out += ["info_alt%d:" % i, dc(name[:-4] + ".SMC")]
    out += ["\teven", "; dest, bytes, file offset, file size (+512: a copier header), checksum, name, other name",
            "info_files:"]
    for i, (tag, dest, nbytes, offset, size, _, name) in enumerate(files):
        alt = "info_alt%d" % i if name.endswith(".SFC") else "0"
        out.append("\tdc.l\t%s,%s_BYTES,%d,%d,%s_SUM,info_name%d,%s" % (dest, tag, offset, size, tag, i, alt))
    out += ["\tdc.l\t0", ""]
    text = "\n".join(out)

    if not a.out.exists() or a.out.read_text() != text:
        a.out.write_text(text)


if __name__ == "__main__":
    main()
